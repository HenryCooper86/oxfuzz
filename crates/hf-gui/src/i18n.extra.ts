// Each entry is [English, Chinese?]; omitted Chinese text preserves locale fallback.

function dictionaries(messages: Record<string, readonly [string, string?]>) {
  const en: Record<string, string> = {};
  const zh: Record<string, string> = {};
  for (const [key, [english, chinese]] of Object.entries(messages)) {
    en[key] = english;
    if (chinese !== undefined) zh[key] = chinese;
  }
  return [en, zh] as const;
}

